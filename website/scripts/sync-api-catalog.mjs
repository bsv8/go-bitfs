// 同步 api-translations.json 与当前生成的 API 文档：
//   1) 删除 catalog 中已不再出现的条目；
//   2) 为新增的中文源注释行补身份映射（源即译文）；
//   3) 把仍为英文的缺失行列出，供人工翻译（写入 stdout）。
// 用法：先运行 generate-api.mjs 使其失败前完成 raw 生成，再运行本脚本。
import {readFile, writeFile} from 'node:fs/promises';

const catalogPath = 'api-translations.json';
const catalog = JSON.parse(await readFile(catalogPath, 'utf8'));
const packages = ['index', 'protocol', 'content', 'pool', 'arbitration', 'wire', 'buyer', 'seller', 'arbiter'];

const normalizeProse = (line) => line
  .replace(/\\([\\()[\]_*#])/g, '$1')
  .replace(/\\-/g, '-');

const collectLines = async (file) => {
  const markdown = await readFile(`generated-api/${file}.md`, 'utf8');
  let inCode = false;
  let inIndex = false;
  const lines = [];
  for (const line of markdown.split('\n')) {
    if (line.startsWith('```')) { inCode = !inCode; continue; }
    if (inCode || line.startsWith('<!--') || line.trim() === '') continue;
    if (line === '---' || line.startsWith('id: ') || line.startsWith('sidebar_position: ')) continue;
    if (line === 'title: API Reference') continue;
    if (line.startsWith('#')) { inIndex = line.startsWith('## Index'); continue; }
    if (inIndex && /^\s*- /.test(line)) continue;
    if (line.startsWith('Generated by ')) continue;
    lines.push(normalizeProse(line));
  }
  return lines;
};

const used = new Set();
for (const pkg of packages) used.add(await collectLines(pkg)).forEach?.(() => {});
const allLines = new Set();
for (const pkg of packages) {
  for (const line of await collectLines(pkg)) allLines.add(line);
}

const next = {};
const englishMissing = [];
for (const key of Object.keys(catalog)) {
  if (allLines.has(key)) next[key] = catalog[key];
}
for (const line of allLines) {
  if (Object.prototype.hasOwnProperty.call(next, line)) continue;
  // 源注释已是中文：直接身份映射；否则列入待人工翻译清单。
  if (/[\u4e00-\u9fff]/.test(line)) {
    next[line] = line;
  } else {
    englishMissing.push(line);
    next[line] = line; // 先占位，保证构建可跑；人工翻译后替换右侧值。
  }
}

await writeFile(catalogPath, JSON.stringify(next, null, 2) + '\n');
if (englishMissing.length) {
  console.log('--- 需要人工翻译的英文行 ---');
  for (const line of englishMissing) console.log(line);
}
console.log(`catalog synced: ${Object.keys(next).length} entries, ${englishMissing.length} pending manual translation`);
